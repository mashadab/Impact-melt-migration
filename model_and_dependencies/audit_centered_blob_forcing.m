function report=audit_centered_blob_forcing(output_dir)
% Independent frozen-flow controls; does NOT alter the continued calculation.
if nargin<1
 root=fileparts(fileparts(mfilename('fullpath')));
 output_dir=strtrim(fileread(fullfile(root,'tmp','centered_continuation_output.txt')));
end
model=fileparts(mfilename('fullpath'));addpath(model);
config=jsondecode(fileread(fullfile(output_dir,'configuration.json')));
out=fullfile(output_dir,'analysis','forcing_control');if ~isfolder(out),mkdir(out);end
source=fileread(fullfile(model,'simple_test_1D_centered_blob_closed.m'));
modified=strrep(source,'function result = simple_test_1D_centered_blob_closed(', ...
 'function result = centered_forcing_control_driver(');
modified=strrep(modified,"fp = fullfile(fileparts(mfilename('fullpath')),'..','initial_conditions','ic');", ...
 sprintf('fp = fullfile(''%s'',''initial_conditions'',''ic'');',strrep(fileparts(model),'''','''''')));
needle='    run_timer = tic;';assert(count(modified,needle)==1);
modified=strrep(modified,needle,sprintf(['    if ~isempty(options.audit_restart)\n' ...
 '        loaded=load(options.audit_restart,''result'');H=loaded.result.final_state.H;\n' ...
 '    end\n%s'],needle));
needle='        fsVec = fs_T + fs_por + fs_fluid_pressure; %adding diffusion and convection equation RHS';
assert(count(modified,needle)==1);
modified=strrep(modified,needle,sprintf(['%s\n' ...
 '        if options.audit_correct_reference,fsVec=fsVec+(Pi_5+Ra)*ones(size(fsVec));end\n'],needle));
needle='        vfmax= max(abs(vf)); %largest solid velocity';assert(count(modified,needle)==1);
modified=strrep(modified,needle,sprintf(['        result=struct(''Grid'',Grid,''d_m'',d,''phi'',phi,''T_dimensionless'',T, ...\n' ...
 '          ''solid_velocity_m_s'',vm*D_T/d,''Darcy_flux_m_s'',qr*D_T/d, ...\n' ...
 '          ''head_Pa'',p_head*eta_0*D_T/d^2,''K_m2'',kc*full(diag(Kdprime)), ...\n' ...
 '          ''kc'',kc,''correct_reference'',options.audit_correct_reference);\n' ...
 '        return; %% frozen-flow control: no thermal advance\n%s'],needle));
fid=fopen(fullfile(out,'centered_forcing_control_driver.m'),'w');fprintf(fid,'%s',modified);fclose(fid);
addpath(out);clean=onCleanup(@()rmpath(out)); %#ok<NASGU>
cases={'initial_legacy','',false,config.kc;'initial_S3_reference','',true,config.kc; ...
 'initial_zero_Darcy','',false,0; ...
 'step100_legacy',config.restart_file,false,config.kc; ...
 'step100_S3_reference',config.restart_file,true,config.kc};
report=struct;
for j=1:size(cases,1)
 label=cases{j,1};caseout=fullfile(out,label);if ~isfolder(caseout),mkdir(caseout);end
 options=struct('max_steps',1,'output_dir',caseout,'legacy_outputs',false, ...
  'evolve_tracers',false,'stop_on_melt_loss',false,'audit_restart',cases{j,2}, ...
  'audit_correct_reference',cases{j,3});
 flow=centered_forcing_control_driver('03321',1e14,50e3,cases{j,4},'effe_vel','temprate_homog_column',options);
 G=flow.Grid.p;d=flow.d_m;vs=flow.solid_velocity_m_s;q=flow.Darcy_flux_m_s;phi=flow.phi;
 carried=flux_upwind(vs,G)*phi;[D,~,~]=build_ops(G);C=D*vs/d;
 [~,iz]=min(abs(G.yf*d-4000));faces=G.Nfx+(0:G.Nx-1)'*(G.Ny+1)+iz;
 [X,Z]=meshgrid(G.xc*d,G.yc*d);p=reshape(phi,G.Ny,G.Nx);
 waterX=false(G.Ny,G.Nx+1);waterZ=false(G.Ny+1,G.Nx);
 waterX(:,2:end-1)=p(:,1:end-1)>1-1e-12 & p(:,2:end)>1-1e-12;
 waterZ(2:end-1,:)=p(1:end-1,:)>1-1e-12 & p(2:end,:)>1-1e-12;
 water=[waterX(:);waterZ(:)];
 [~,ix]=min(abs(G.xc*d-10100));[~,jj]=min(abs(G.yc*d-3950));
 id=(ix-1)*G.Ny+jj;top=G.Nfx+(ix-1)*(G.Ny+1)+jj+1;
 row=struct('case',label,'kc',flow.kc,'S3_reference_correction',flow.correct_reference, ...
  'Q_carried_down_m3_per_year_per_m_depth',-sum(carried(faces))*G.dx*d*3.154e7, ...
  'Q_Darcy_down_m3_per_year_per_m_depth',-sum(q(faces))*G.dx*d*3.154e7, ...
  'sample_top_solid_down_m_per_year',-vs(top)*3.154e7, ...
  'sample_top_Darcy_down_m_per_year',-q(top)*3.154e7, ...
  'sample_C_per_year',C(id)*3.154e7,'sample_phi',phi(id),'sample_x_m',X(id),'sample_z_m',Z(id), ...
  'max_abs_vs_m_per_year',max(abs(vs))*3.154e7, ...
  'max_abs_q_m_per_year',max(abs(q))*3.154e7, ...
  'max_abs_vs_on_pure_water_faces_m_per_year',max(abs(vs(water)))*3.154e7, ...
  'max_abs_q_on_pure_water_faces_m_per_year',max(abs(q(water)))*3.154e7, ...
  'max_abs_actual_liquid_flux_on_pure_water_faces_m_per_year',max(abs((carried(water)+q(water))))*3.154e7, ...
  'max_abs_mixture_divergence_per_year',max(abs(D*(vs+q)/d))*3.154e7);
 report.(label)=row;save(fullfile(out,[label '.mat']),'flow','row');
 fprintf('CENTERED_FORCING_CONTROL %s\n',jsonencode(row));
end
report.scope='Frozen-flow sensitivity only; these controls do not change or validate the ongoing trajectory.';
fid=fopen(fullfile(out,'forcing_control.json'),'w');fprintf(fid,'%s',jsonencode(report));fclose(fid);
end
