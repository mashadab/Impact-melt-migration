function report=audit_centered_water_permeability(output_dir)
% Frozen-flow controls from the CORRECTED shared solver. No time advancement.
model=fileparts(mfilename('fullpath'));root=fileparts(model);addpath(model);
if nargin<1,output_dir=fullfile(root,'Output',['centered_water_permeability_proof_' datestr(now,'yyyymmdd_HHMMSS')]);end
assert(~isfolder(output_dir));mkdir(output_dir);mkdir(fullfile(output_dir,'source'));
diary(fullfile(output_dir,'audit.log'));clean=onCleanup(@()diary('off')); %#ok<NASGU>
provenance=jsondecode(fileread(fullfile(root,'docs','CENTERED_WATER_S3_PROVENANCE.json')));
reference=provenance.verification.output_dir;
saved=load(fullfile(reference,'noflow_kc_1.850e-08.mat'),'result');saved=saved.result;
source=fileread(fullfile(reference,'source','darcy_stokes_2D_cases.m.txt'));
copyfile(fullfile(reference,'source','darcy_stokes_2D_cases.m.txt'),fullfile(output_dir,'source','corrected_parent.m.txt'));
driver=strrep(source,'function result = darcy_stokes_2D_cases(', ...
 'function result = centered_permeability_frozen_flow(');
needle='    run_timer = tic;';assert(count(driver,needle)==1);
driver=strrep(driver,needle,sprintf('    H=options.frozen_H; %% frozen actual saved state, same for both kc\n%s',needle));
needle='        vfmax= max(abs(vf)); %largest solid velocity';assert(count(driver,needle)==1);
capture=[
 '        result=struct(''Grid'',Grid,''d_m'',d,''phi'',phi,''T_dimensionless'',T,''H'',H, ...' newline ...
 '          ''solid_velocity_m_s'',vm*D_T/d,''Darcy_flux_m_s'',qr*D_T/d, ...' newline ...
 '          ''fluid_velocity_m_s'',vf*D_T/d,''pressure_head_Pa'',p_head*eta_0*D_T/d^2, ...' newline ...
 '          ''permeability_m2'',kc*full(diag(Kdprime)),''kc'',kc, ...' newline ...
 '          ''correct_head_reference'',options.correct_head_reference);' newline ...
 '        residual=N''*(L*u-fs);denominator=abs(N''*L)*abs(u)+abs(N''*fs);' newline ...
 '        result.max_componentwise_free_residual=max(abs(residual)./max(denominator,realmin));' newline ...
 '        return; % frozen flow: no enthalpy transport or time update' newline];
driver=strrep(driver,needle,[capture needle]);
fid=fopen(fullfile(output_dir,'source','centered_permeability_frozen_flow.m'),'w');fprintf(fid,'%s',driver);fclose(fid);
addpath(fullfile(output_dir,'source'));path_clean=onCleanup(@()rmpath(fullfile(output_dir,'source'))); %#ok<NASGU>
initial=saved.full_H(:,1);later=saved.final_state.H;
cases={'initial_high',initial,0,1.85e-8;'initial_low',initial,0,1.85e-16; ...
 'same_1yr_state_high',later,1,1.85e-8;'same_1yr_state_low',later,1,1.85e-16};
report=struct('source','corrected shared S3 solver used by verified one-year run', ...
 'reference_run',reference,'baseline_sha256',provenance.solver_sha256, ...
 'scope','Identical frozen H, phi, T, geometry, rheology, gravity and walls within each pair; only kc changes. The low-kc one-year-state control is not a low-kc evolved trajectory.');
flows=cell(4,1);rows=cell(4,1);
for j=1:4
 label=cases{j,1};options=struct('max_steps',1,'output_dir',fullfile(output_dir,label), ...
  'frozen_H',cases{j,2},'correct_head_reference',true,'use_actual_conductivity_timestep',true);
 flow=centered_permeability_frozen_flow('centered_water','03321',1e14,50e3,cases{j,4},'effe_vel','case_setup',options);
 assert(flow.correct_head_reference);G=flow.Grid.p;d=flow.d_m;YEAR=3.154e7;
 [D,~,~]=build_ops(G);D=D/d;vs=flow.solid_velocity_m_s;q=flow.Darcy_flux_m_s;
 carried=flux_upwind(vs,G)*flow.phi;C=D*vs;flow.dilation_rate_per_s=(1-flow.phi).*C;
 flow.solid_divergence_per_s=C;flow.carried_liquid_flux_m_s=carried;
 [~,iz]=min(abs(G.yf*d-4000));faces=G.Nfx+iz+(0:G.Nx-1)'*(G.Ny+1);
 [X,Z]=meshgrid(G.xc*d,G.yc*d);wet=flow.phi>=1e-4 & flow.phi<=.9;
 V=G.V*d^2;A=G.A(faces)*d;
 [~,ix]=min(abs(G.xc*d-10100));[~,jj]=min(abs(G.yc*d-3950));
 id=(ix-1)*G.Ny+jj;top=G.Nfx+(ix-1)*(G.Ny+1)+jj+1;
 row=struct('case',label,'frozen_state_time_years',cases{j,3},'kc_m2',flow.kc, ...
  'Q_carried_down_m3_year_per_m_depth',-sum(carried(faces).*A)*YEAR, ...
  'Q_Darcy_down_m3_year_per_m_depth',-sum(q(faces).*A)*YEAR, ...
  'Q_net_down_m3_year_per_m_depth',-sum((carried(faces)+q(faces)).*A)*YEAR, ...
  'max_abs_vs_m_year',max(abs(vs))*YEAR,'max_abs_q_m_year',max(abs(q))*YEAR, ...
  'sample_phi',flow.phi(id),'sample_top_vs_down_m_year',-vs(top)*YEAR, ...
  'sample_top_q_down_m_year',-q(top)*YEAR, ...
  'sample_x_m',X(id),'sample_z_m',Z(id), ...
  'max_positive_wet_dilation_per_year',max([0;flow.dilation_rate_per_s(wet)])*YEAR, ...
  'positive_wet_dilation_volume_rate_m3_year_per_m_depth',sum(max(flow.dilation_rate_per_s(wet),0).*V(wet))*YEAR, ...
  'max_abs_mixture_divergence_per_year',max(abs(D*(vs+q)))*YEAR, ...
  'max_componentwise_free_residual',flow.max_componentwise_free_residual);
 flow.interface_faces=faces;flows{j}=flow;rows{j}=row;report.(label)=row;
 save(fullfile(output_dir,[label '.mat']),'flow','row');
 fprintf('CORRECTED_PERMEABILITY_CONTROL %s\n',jsonencode(row));
end
for j=[1 3]
 assert(isequaln(flows{j}.phi,flows{j+1}.phi) && isequaln(flows{j}.T_dimensionless,flows{j+1}.T_dimensionless));
end
report.matched_thermodynamics_verified=true;
report.initial_carried_Q_ratio=rows{1}.Q_carried_down_m3_year_per_m_depth/rows{2}.Q_carried_down_m3_year_per_m_depth;
report.same_1yr_net_Q_ratio=rows{3}.Q_net_down_m3_year_per_m_depth/rows{4}.Q_net_down_m3_year_per_m_depth;
fid=fopen(fullfile(output_dir,'permeability_proof.json'),'w');fprintf(fid,'%s',jsonencode(report));fclose(fid);
writetable(struct2table(vertcat(rows{:})),fullfile(output_dir,'matched_flow_comparison.csv'));
fid=fopen(fullfile(root,'tmp','centered_water_permeability_proof_output.txt'),'w');fprintf(fid,'%s',output_dir);fclose(fid);
fprintf('CORRECTED_PERMEABILITY_PROOF_OUTPUT %s\n',output_dir);
end
