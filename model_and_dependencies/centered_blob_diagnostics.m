function diagnostic=centered_blob_diagnostics(Grid,d,Dthermal,tc,dt,H0,T0,phi0,H1,T1,phi1,vm,qr,p_head,K,kappaFace,Ae,Aq,latent)
% Read-only accounting of one actual update. Does not modify the solution.
% Fluxes are Cartesian volumes per unit out-of-plane depth.
G=Grid.p;YEAR=3.154e7;dt_s=dt*tc;D=build_ops(G)/d;
vs=vm*Dthermal/d;q=qr*Dthermal/d;
vbulk=flux_upwind(vs,G)*phi0;
C=D*vs;
bulk=-D*vbulk+phi0.*C;dilation=(1-phi0).*C;
total=(phi1-phi0)/dt_s;
phase=total+D*(vbulk+q);
constraint=-D*q-C;
Hadv=Ae*H0;Hdarcy=Aq*H0;Hcond=-Dthermal/d*kappaFace*(build_gradient(G)*T0);
dHadv=-dt*build_ops(G)*Hadv;dHdarcy=-dt*build_ops(G)*Hdarcy;
dHcond=-dt_s*D*Hcond;
Hreconstructed=H0+dHadv+dHdarcy+dHcond;
[X,Z]=meshgrid(G.xc*d,G.yc*d);lower=Z(:)<4000;
initial_dry=~(X(:)>5000 & X(:)<15000 & Z(:)>4000);
[~,iz]=min(abs(G.yf*d-4000));faces=G.Nfx+(0:G.Nx-1)'*(G.Ny+1)+iz;
V=G.V*d^2;A=G.dx*d;
dry=phi0==0;wet=phi0>=1e-6 & phi0<=.5;
born=dry & lower & phi1>1e-8;
water=phi0>1-1e-12;
diagnostic=struct('phi_before',phi0,'phi_after',phi1,'T_before_K',T0*173+100, ...
 'T_after_K',T1*173+100,'H_before',H0,'H_after',H1, ...
 'solid_velocity_m_s',vs,'darcy_flux_m_s',q,'carried_liquid_flux_m_s',vbulk, ...
 'solid_divergence_per_s',C,'bulk_transport_rate_per_s',bulk, ...
 'dilation_rate_per_s',dilation,'effective_phase_residual_per_s',phase, ...
 'mixture_constraint_correction_per_s',constraint, ...
 'permeability_m2',full(diag(K))*1.85e-8, ...
 'pressure_head_dimensionless',p_head, ...
 'dH_bulk',dHadv,'dH_Darcy',dHdarcy,'dH_conduction',dHcond, ...
 'dt_years',dt_s/YEAR,'interface_faces',faces,'cell_volume_m3_per_m_depth',V);
row=struct('max_phi_lower',max(phi1(lower)),'max_phi_initially_dry',max(phi1(initial_dry)), ...
 'liquid_lower_m3_per_m_depth',sum(phi1(lower).*V(lower)), ...
 'Q_carried_down_m3_per_year_per_m_depth',-sum(vbulk(faces))*A*YEAR, ...
 'Q_Darcy_down_m3_per_year_per_m_depth',-sum(q(faces))*A*YEAR, ...
 'Q_total_down_m3_per_year_per_m_depth',-sum(vbulk(faces)+q(faces))*A*YEAR, ...
 'lower_delta_liquid_m3_per_m_depth',sum((phi1(lower)-phi0(lower)).*V(lower)), ...
 'lower_bulk_flux_delta_liquid_m3_per_m_depth',sum((-dt_s*D*vbulk).*lower.*V), ...
 'lower_Darcy_flux_delta_liquid_m3_per_m_depth',sum((-dt_s*D*q).*lower.*V), ...
 'lower_effective_phase_delta_liquid_m3_per_m_depth',sum(phase.*lower.*V)*dt_s, ...
 'max_abs_vs_m_per_year',max(abs(vs))*YEAR, ...
 'max_abs_q_m_per_year',max(abs(q))*YEAR, ...
 'max_abs_mixture_divergence_per_year',max(abs(C+D*q))*YEAR, ...
 'max_positive_dilation_wet_per_year',safe_max(dilation(wet))*YEAR, ...
 'max_abs_dilation_exactly_dry_per_year',safe_max(abs(C(dry)))*YEAR, ...
 'max_abs_dilation_pure_water_per_year',safe_max(abs(C(water)))*YEAR, ...
 'newly_wet_lower_cells',sum(born),'max_H_reconstruction_error',max(abs(H1-Hreconstructed)), ...
 'max_phi_budget_closure_error_per_year',max(abs(total-bulk-dilation-phase-constraint))*YEAR, ...
 'T_min_K',min(T1)*173+100,'T_max_K',max(T1)*173+100);
if any(born)
 ids=find(born);[~,j]=max(phi1(ids));id=ids(j);
 sample=struct('cell_id',id,'x_m',X(id),'z_m',Z(id),'phi_before',phi0(id), ...
  'phi_after',phi1(id),'bulk_delta_phi',bulk(id)*dt_s, ...
  'dilation_delta_phi',dilation(id)*dt_s,'phase_residual_delta_phi',phase(id)*dt_s, ...
  'constraint_delta_phi',constraint(id)*dt_s,'H_bulk_gain',dHadv(id), ...
  'H_Darcy_gain',dHdarcy(id),'H_conduction_gain',dHcond(id));
else,sample=struct;end
diagnostic.row=row;diagnostic.newly_wet_sample=sample;diagnostic.latent_dimensionless=latent;
diagnostic.interpretation=['Discrete accounting. Bulk term includes upwind truncation error. ' ...
 'Phase residual is not an independent gross melting measurement. Algebraic budget closure is not validation.'];
end
function Gp=build_gradient(G)
[~,Gp,~]=build_ops(G);
end
function value=safe_max(values)
if isempty(values),value=0;else,value=max(values);end
end
