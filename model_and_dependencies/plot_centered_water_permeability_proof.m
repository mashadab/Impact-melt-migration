function plot_centered_water_permeability_proof(output_dir)
% Figures from actual frozen-flow solves. No interpolation of state or time.
if nargin<1
 root=fileparts(fileparts(mfilename('fullpath')));
 output_dir=strtrim(fileread(fullfile(root,'tmp','centered_water_permeability_proof_output.txt')));
end
r=jsondecode(fileread(fullfile(output_dir,'permeability_proof.json')));
hi=r.same_1yr_state_high;lo=r.same_1yr_state_low;
navy=[.12 .24 .38];blue=[.10 .47 .72];orange=[.88 .40 .16];gray=[.38 .43 .48];
labels={'1.85e-8','1.85e-16'};
f=figure('Visible','off','Color','w','Units','inches','Position',[.3 .3 14 7.6], ...
 'PaperUnits','inches','PaperPosition',[0 0 14 7.6],'PaperSize',[14 7.6]);
annotation(f,'textbox',[.055 .89 .91 .07],'String','What higher permeability actually changes', ...
 'LineStyle','none','FontName','Arial','FontSize',22,'Color',navy,'Interpreter','none');
annotation(f,'textbox',[.055 .83 .91 .05], ...
 'String','Corrected shared S3 solver | identical temperature, melt fraction and geometry within each comparison', ...
 'LineStyle','none','FontName','Arial','FontSize',12,'Color',gray,'Interpreter','none');
positions={[.065 .28 .24 .42],[.395 .28 .24 .42],[.725 .28 .24 .42]};
ax=axes('Parent',f,'Position',positions{1});
values=[r.initial_high.sample_top_vs_down_m_year,r.initial_low.sample_top_vs_down_m_year];
b=bar(ax,values,.5,'FaceColor','flat');b.CData=[orange;blue];ylim(ax,[0 75]);
set(ax,'XTick',1:2,'XTickLabel',labels);ylabel(ax,'Downward ice speed [m/year]','Interpreter','none');
for k=1:2,text(ax,k,values(k)+2,sprintf('%.2f',values(k)), ...
 'HorizontalAlignment','center','FontSize',14,'FontWeight','bold','Interpreter','none');end
xlabel(ax,'kc [m^2]','Interpreter','none');
annotation(f,'textbox',[.06 .73 .26 .065],'String',{'A  First contact with dry ice','Bulk speed is almost the same'}, ...
 'LineStyle','none','FontName','Arial','FontSize',13,'Interpreter','none');
annotation(f,'textbox',[.07 .17 .25 .065],'String',{'Same initial dry-interface face','Darcy flux = 0 for both cases'}, ...
 'LineStyle','none','FontName','Arial','FontSize',11,'Color',gray,'Interpreter','none');

ax=axes('Parent',f,'Position',positions{2});
data=[hi.Q_carried_down_m3_year_per_m_depth hi.Q_Darcy_down_m3_year_per_m_depth hi.Q_net_down_m3_year_per_m_depth; ...
 lo.Q_carried_down_m3_year_per_m_depth lo.Q_Darcy_down_m3_year_per_m_depth lo.Q_net_down_m3_year_per_m_depth]/1e6;
b=bar(ax,data,'grouped');b(1).FaceColor=gray;b(2).FaceColor=blue;b(3).FaceColor=orange;
yline(ax,0,'Color',navy);ylim(ax,[-24 27]);set(ax,'XTick',1:2,'XTickLabel',labels);
ylabel(ax,'Downward Q [10^6 m^3/year per m depth]','Interpreter','none');xlabel(ax,'kc [m^2]','Interpreter','none');
legend(ax,{'Carried with ice','Relative Darcy','Net'},'Location','northoutside','Orientation','horizontal', ...
 'FontSize',8.5,'Box','off','Interpreter','none');
annotation(f,'textbox',[.39 .73 .28 .065],'String',{'B  Same one-year melt shape','Relative flow changes transport'}, ...
 'LineStyle','none','FontName','Arial','FontSize',13,'Interpreter','none');
annotation(f,'textbox',[.395 .17 .27 .065], ...
 'String',sprintf('High kc: %.2f - %.2f = %.2f\nLow kc: %.3f + %.3g = %.3f', ...
 data(1,2),abs(data(1,1)),data(1,3),data(2,1),data(2,2),data(2,3)), ...
 'LineStyle','none','FontName','Arial','FontSize',11,'Color',gray,'Interpreter','none');

ax=axes('Parent',f,'Position',positions{3});
values=[hi.max_positive_wet_dilation_per_year,lo.max_positive_wet_dilation_per_year];
b=bar(ax,values,.5,'FaceColor','flat');b.CData=[orange;blue];
set(ax,'XTick',1:2,'XTickLabel',labels,'YScale','log');ylim(ax,[1e-8 1e3]);
ylabel(ax,'Maximum positive (1-phi) div(v_s) [1/year]','Interpreter','none');xlabel(ax,'kc [m^2]','Interpreter','none');
for k=1:2,text(ax,k,values(k)*2.1,sprintf('%.3g',values(k)), ...
 'HorizontalAlignment','center','FontSize',13,'FontWeight','bold','Interpreter','none');end
annotation(f,'textbox',[.72 .73 .28 .065],'String',{'C  Same one-year melt shape','Expansion in partly molten ice'}, ...
 'LineStyle','none','FontName','Arial','FontSize',13,'Interpreter','none');
annotation(f,'textbox',[.725 .17 .27 .065],'String',{'Maximum over 0.0001 <= phi <= 0.9','Local rate; not net liquid production'}, ...
 'LineStyle','none','FontName','Arial','FontSize',11,'Color',gray,'Interpreter','none');
for ax=findall(f,'Type','axes')'
 set(ax,'FontName','Arial','FontSize',10.5,'TickLabelInterpreter','none','Box','off','Layer','top');grid(ax,'on');ax.GridAlpha=.12;
 ax.YMinorGrid='off';
end
annotation(f,'textbox',[.055 .05 .92 .075], ...
 'String',sprintf(['Across z = 4 km, net downward transfer is %.2fx larger when only kc changes.\n' ...
 'B-C re-solve the high-kc one-year state at each kc; the low-kc control is not a separately evolved one-year run.'],r.same_1yr_net_Q_ratio), ...
 'LineStyle','none','FontName','Arial','FontSize',12,'Color',navy,'Interpreter','none');
drawnow;print(f,fullfile(output_dir,'02_matched_state_numerical_proof.png'),'-dpng','-r170');
print(f,fullfile(output_dir,'02_matched_state_numerical_proof.svg'),'-dsvg');close(f);

% A minimal explanation figure: exact computed fluxes and conservation.
f=figure('Visible','off','Color','w','Units','inches','Position',[.3 .3 12 7.1], ...
 'PaperUnits','inches','PaperPosition',[0 0 12 7.1],'PaperSize',[12 7.1]);
annotation(f,'textbox',[.055 .88 .91 .07],'String','Why melt moves faster at higher kc', ...
 'LineStyle','none','FontName','Arial','FontSize',23,'Color',navy,'Interpreter','none');
annotation(f,'textbox',[.055 .80 .91 .06], ...
 'String','Liquid flux = liquid carried with the ice + liquid moving relative to the ice', ...
 'LineStyle','none','FontName','Arial','FontSize',15,'Interpreter','none');
annotation(f,'textbox',[.055 .64 .41 .125],'String',{'LOW kc = 1.85e-16','Relative drainage is tiny.','Most water moves with the ice.'}, ...
 'LineStyle','none','FontName','Arial','FontSize',16,'Color',blue,'Interpreter','none');
annotation(f,'textbox',[.56 .64 .41 .125],'String',{'HIGH kc = 1.85e-8','Water drains through wet material.','Ice motion and pressure adjust.'}, ...
 'LineStyle','none','FontName','Arial','FontSize',16,'Color',orange,'Interpreter','none');
annotation(f,'line',[.50 .50],[.23 .76],'Color',[.85 .87 .89]);
annotation(f,'arrow',[.18 .18],[.58 .34],'Color',gray,'LineWidth',6,'HeadWidth',17,'HeadLength',17);
annotation(f,'textbox',[.225 .41 .25 .14], ...
 'String',sprintf('Carried: +%.3f\nDarcy: +%.2g\nNet: +%.3f', ...
 lo.Q_carried_down_m3_year_per_m_depth/1e6,lo.Q_Darcy_down_m3_year_per_m_depth/1e6,lo.Q_net_down_m3_year_per_m_depth/1e6), ...
 'LineStyle','none','FontName','Arial','FontSize',15,'Interpreter','none');
annotation(f,'arrow',[.65 .65],[.58 .34],'Color',blue,'LineWidth',9,'HeadWidth',21,'HeadLength',21);
annotation(f,'arrow',[.75 .75],[.34 .58],'Color',gray,'LineWidth',6,'HeadWidth',17,'HeadLength',17);
annotation(f,'textbox',[.79 .40 .20 .17], ...
 'String',sprintf('Darcy: +%.2f\nCarried: %.2f\nNet: +%.2f', ...
 hi.Q_Darcy_down_m3_year_per_m_depth/1e6,hi.Q_carried_down_m3_year_per_m_depth/1e6,hi.Q_net_down_m3_year_per_m_depth/1e6), ...
 'LineStyle','none','FontName','Arial','FontSize',15,'Interpreter','none');
annotation(f,'textbox',[.055 .22 .91 .07], ...
 'String','Relative flow also permits expansion / compaction of the ice framework: div(v_s) = -div(q).', ...
 'LineStyle','none','FontName','Arial','FontSize',14,'Color',navy,'Interpreter','none');
annotation(f,'textbox',[.055 .08 .91 .11], ...
 'String',{'Same frozen one-year melt shape; only kc changes. Values: 10^6 m^3/year per m depth, downward positive.', ...
 'Arrow widths are schematic. At an exactly dry interface, relative Darcy flow is zero in both cases.'}, ...
 'LineStyle','none','FontName','Arial','FontSize',11,'Color',gray,'Interpreter','none');
drawnow;print(f,fullfile(output_dir,'01_simple_mechanism.png'),'-dpng','-r170');
print(f,fullfile(output_dir,'01_simple_mechanism.svg'),'-dsvg');close(f);
fprintf('PERMEABILITY_FIGURES %s\n',output_dir);
end
