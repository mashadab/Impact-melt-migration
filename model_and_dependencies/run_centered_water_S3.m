function result=run_centered_water_S3(final_years,output_dir)
% Centered-water setup in the corrected SHARED porosity-wave/Europa solver.
% Example: r=run_centered_water_S3(1); % fresh initial condition, one year
if nargin<1,final_years=1;end
root=fileparts(mfilename('fullpath'));addpath(root);
if nargin<2
 output_dir=fullfile(root,'..','Output',['centered_water_S3_' datestr(now,'yyyymmdd_HHMMSS')]);
end
assert(~isfolder(output_dir),'Choose a new output directory; previous runs are preserved.');
mkdir(output_dir);mkdir(fullfile(output_dir,'source'));
for name={'darcy_stokes_2D_cases.m','run_darcy_stokes_case.m','run_centered_water_S3.m', ...
 'record_centered_water_step.m','centered_blob_diagnostics.m','build_stokes_grid_cyl.m', ...
 'build_grid.m','build_ops.m','build_bnd.m','solve_lbvp.m','comp_mean.m', ...
 'comp_mean_corners.m','barrViscPhase.m','enthMelt.m','flux_upwind.m', ...
 'build_adv_op.m','smoothness.m','comp_limiter.m'}
 copyfile(fullfile(root,name{1}),fullfile(output_dir,'source',[name{1} '.txt']));
end
diary(fullfile(output_dir,'run.log'));clean=onCleanup(@()diary('off')); %#ok<NASGU>
options=struct('kc',1.85e-8,'max_steps',200000,'final_years',final_years, ...
 'snapshot_steps',[0 1:10 25 50 100],'snapshot_interval_years',.1, ...
 'checkpoint_steps',250,'correct_head_reference',true, ...
 'use_actual_conductivity_timestep',true,'stop_on_melt_loss',false, ...
 'evolve_tracers',false,'legacy_outputs',false,'output_dir',output_dir);
try
 result=run_darcy_stokes_case('centered_water',options);
 initial_state=struct('H',result.full_H(:,1), ...
  'T_dimensionless',(result.full_T_K(:,1)-100)/173,'phi',result.full_phi(:,1), ...
  'Grid',result.Grid,'d_m',result.length_scale_m,'temperature_scale_K',173,'temperature_offset_K',100);
 save(fullfile(output_dir,'initial_state.mat'),'initial_state');
 assert(result.correct_head_reference && result.use_actual_conductivity_timestep);
 assert(result.permeability_exponent==3 && isequal(result.mesh,[100 120]));
 assert(strcmp(result.Grid.p.geom,'cartesian') && result.enthalpy_dirichlet_count==0);
 assert(max([result.max_boundary_solid_flux result.max_boundary_darcy_flux ...
  result.max_boundary_advective_heat_flux result.max_boundary_conductive_heat_flux])<1e-12);
 assert(result.max_enthalpy_balance_error<1e-8*abs(result.initial_enthalpy_total));
 summary=struct('status',result.status,'step',result.completed_steps, ...
  'time_years',result.time_years(end),'target_years',final_years, ...
  'solver','darcy_stokes_2D_cases','case_key','centered_water', ...
  'correct_head_reference',result.correct_head_reference,'permeability_exponent',3, ...
  'relative_enthalpy_error',result.max_enthalpy_balance_error/abs(result.initial_enthalpy_total));
 fid=fopen(fullfile(output_dir,'summary.json'),'w');fprintf(fid,'%s',jsonencode(summary));fclose(fid);
 writetable(array2table(result.history,'VariableNames',result.history_columns),fullfile(output_dir,'history.csv'));
 if strcmp(result.status,'completed'),assert(result.time_years(end)>=final_years-1e-10);end
 fprintf('CORRECTED_CENTERED_WATER %s\nOUTPUT %s\n',jsonencode(summary),output_dir);
catch exception
 record=struct('status','failed','message',exception.message, ...
  'report',getReport(exception,'extended','hyperlinks','off'));
 fid=fopen(fullfile(output_dir,'error.json'),'w');fprintf(fid,'%s',jsonencode(record));fclose(fid);
 rethrow(exception)
end
end
