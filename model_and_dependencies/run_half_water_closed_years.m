function result=run_half_water_closed_years(final_years,kc,output_dir)
% Time-limited run of the minimal half-water test, with unchanged physics.
% The original three-line test copy remains untouched. An archived driver
% adds only a final-time cap, status reporting, and full-state checkpoints.
if nargin<1,final_years=1;end
if nargin<2,kc=1.85e-8;end
root=fileparts(mfilename('fullpath'));addpath(root);
if nargin<3
 output_dir=fullfile(root,'..','Output',['half_water_years_' datestr(now,'yyyymmdd_HHMMSS')]);
end
validateattributes(final_years,{'numeric'},{'scalar','finite','positive'});
validateattributes(kc,{'numeric'},{'scalar','finite','nonnegative'});
if ~isfolder(output_dir),mkdir(output_dir);end
source_dir=fullfile(output_dir,'source');mkdir(source_dir);
diary(fullfile(output_dir,'run.log'));clean=onCleanup(@()diary('off')); %#ok<NASGU>
parent=fullfile(root,'simple_test_1D_half_water_closed.m');
source=fileread(parent);driver=source;
driver=one_replace(driver,'function result = simple_test_1D_half_water_closed(', ...
 'function result = half_water_time_driver(');
% The archived driver lives outside the model folder; retain the SAME input.
driver=one_replace(driver, ...
 'fp = fullfile(fileparts(mfilename(''fullpath'')),''..'',''initial_conditions'',''ic'');', ...
 sprintf('fp = fullfile(''%s'',''initial_conditions'',''ic'');',strrep(fileparts(root),'''','''''')));
needle='    run_timer = tic;';
extra=sprintf(['%s\n' ...
 '    %% TIME RUN: actual completed states only; no state/time interpolation.\n' ...
 '    half_save_years=unique([.01 .1 .25 .5 .75 options.final_years]);\n' ...
 '    half_save_years=half_save_years(half_save_years<=options.final_years);\n' ...
 '    initial_state=struct(''H'',H,''T_dimensionless'',T,''phi'',phi,''Grid'',Grid, ...\n' ...
 '      ''d_m'',d,''temperature_scale_K'',DT,''temperature_offset_K'',T_t);\n' ...
 '    save(fullfile(options.output_dir,''initial_state.mat''),''initial_state'');\n'],needle);
driver=one_replace(driver,needle,extra);
needle='        %% non-linear thermal conducitivity matricies';
extra=sprintf(['        %% TIME RUN: retain inherited adaptive dt; shorten only the final step.\n' ...
 '        dt=min(dt,max(0,options.final_years-tTot)*3.154e7/t_c);\n' ...
 '        half_flow_time=tTot;\n\n%s'],needle);
driver=one_replace(driver,needle,extra);
needle='        if i==1 || mod(i,50)==0';
extra=sprintf(['        %% TIME RUN: progress reporting does not feed back into the equations.\n' ...
 '        half_reached=tTot>=options.final_years-8*eps(max(1,options.final_years));\n' ...
 '        if i==1 || mod(i,50)==0 || half_reached\n' ...
 '            progress=struct(''status'',''running'',''completed_steps'',i, ...\n' ...
 '              ''time_years'',tTot,''target_years'',options.final_years, ...\n' ...
 '              ''dt_years'',dt*t_c/3.154e7,''wall_seconds'',toc(run_timer), ...\n' ...
 '              ''T_min_K'',min(T)*DT+T_t,''T_max_K'',max(T)*DT+T_t, ...\n' ...
 '              ''max_phi_initial_lower_half'',max(phi(Y(:)<.4)), ...\n' ...
 '              ''relative_enthalpy_error'',energy_error/result.initial_enthalpy_total, ...\n' ...
 '              ''max_solid_speed_m_per_year'',max(abs(vm))*D_T/d*3.154e7, ...\n' ...
 '              ''max_Darcy_flux_m_per_year'',max(abs(qr))*D_T/d*3.154e7);\n' ...
 '            jf=fopen(fullfile(options.output_dir,''progress.tmp.json''),''w'');\n' ...
 '            fprintf(jf,''%%s'',jsonencode(progress));fclose(jf);\n' ...
 '            movefile(fullfile(options.output_dir,''progress.tmp.json''), ...\n' ...
 '              fullfile(options.output_dir,''progress.json''),''f'');\n' ...
 '        end\n%s'],needle);
driver=one_replace(driver,needle,extra);
driver=one_replace(driver,'        if any(i==options.snapshot_steps)', ...
 ['        half_milestone=any(half_save_years>half_flow_time & half_save_years<=tTot);' newline ...
  '        if any(i==options.snapshot_steps) || mod(i,1000)==0 || half_milestone || half_reached']);
needle='            save(result.output_file,''result'');';
extra=sprintf(['            result.completed_steps=i;\n' ...
 '            checkpoint=struct(''completed_steps'',i,''time_years'',tTot, ...\n' ...
 '              ''flow_time_years'',half_flow_time,''H'',H,''T_dimensionless'',T, ...\n' ...
 '              ''phi'',phi,''Grid'',Grid,''d_m'',d, ...\n' ...
 '              ''solid_velocity_m_s'',vm*D_T/d,''darcy_flux_m_s'',qr*D_T/d, ...\n' ...
 '              ''pressure_head_dimensionless'',p_head,''dt_years'',dt*t_c/3.154e7);\n' ...
 '            checkpoint_file=fullfile(options.output_dir,''states'',sprintf(''state_%%08d.mat'',i));\n' ...
 '            save(checkpoint_file,''checkpoint'');\n%s'],needle);
driver=one_replace(driver,needle,extra);
needle='        % condition for ending simulation';
driver=one_replace(driver,needle,sprintf('        if half_reached,break;end %% TIME RUN: requested physical time reached\n\n%s',needle));
needle='    if ~strcmp(result.status,''failed''), result.status = ''completed''; end';
driver=one_replace(driver,needle,sprintf(['    if ~strcmp(result.status,''failed'')\n' ...
 '        if half_reached,result.status=''completed'';else,result.status=''step_limit'';end\n' ...
 '    end\n' ...
 '    result.target_years=options.final_years;\n' ...
 '    result.wall_seconds=toc(run_timer);\n']));
fid=fopen(fullfile(source_dir,'half_water_time_driver.m'),'w');fprintf(fid,'%s',driver);fclose(fid);
copyfile(parent,fullfile(source_dir,'minimal_parent_used.m.txt'));
copyfile(mfilename('fullpath')+string('.m'),fullfile(source_dir,'run_half_water_closed_years.m.txt'));
mkdir(fullfile(output_dir,'states'));
config=struct('final_years',final_years,'kc',kc,'seconds_per_year',3.154e7, ...
 'max_steps',200000,'grid',[100 120],'domain_x_km',[0 20],'domain_z_km',[-2 10], ...
 'interface_z_km',4,'initial_upper_phi',1,'initial_lower_phi',0,'initial_T_K',273, ...
 'full_checkpoint_steps',1000,'full_checkpoint_year_milestones',unique([.01 .1 .25 .5 .75 final_years]), ...
 'source_parent',parent,'actual_driver',fullfile(source_dir,'half_water_time_driver.m'), ...
 'physical_changes_from_minimal_parent','none; only run duration, status, and saving controls');
write_json(fullfile(output_dir,'configuration.json'),config);
addpath(source_dir);path_clean=onCleanup(@()rmpath(source_dir)); %#ok<NASGU>
options=struct('max_steps',config.max_steps,'snapshot_steps',[0 1 100], ...
 'final_years',final_years,'legacy_outputs',false,'evolve_tracers',false, ...
 'stop_on_melt_loss',false,'output_dir',output_dir);
try
 result=half_water_time_driver('03321',1e14,50e3,kc,'effe_vel','temprate_homog_column',options);
 progress=struct('status',result.status,'completed_steps',result.completed_steps, ...
  'time_years',result.time_years(end),'target_years',final_years,'wall_seconds',result.wall_seconds, ...
  'relative_enthalpy_error',result.max_enthalpy_balance_error/abs(result.initial_enthalpy_total), ...
  'T_min_K',min(result.final_state.T_dimensionless)*173+100, ...
  'T_max_K',max(result.final_state.T_dimensionless)*173+100);
 write_json(fullfile(output_dir,'progress.json'),progress);
 writetable(array2table(result.history,'VariableNames',result.history_columns),fullfile(output_dir,'history.csv'));
 run_half_water_closed_test(output_dir); % saved-data plotting only
 assert(strcmp(result.status,'completed') && abs(progress.time_years-final_years)<1e-10, ...
  'The requested final time was not reached; inspect the saved progress and states.');
 fprintf('HALF_WATER_TIME_RUN_COMPLETE %s\n',output_dir);
catch exception
 write_json(fullfile(output_dir,'error.json'),struct('message',exception.message, ...
  'identifier',exception.identifier,'report',getReport(exception,'extended','hyperlinks','off')));
 rethrow(exception)
end
end

function out=one_replace(in,needle,replacement)
assert(count(in,needle)==1,'Expected source block is not unique: %s',needle);
out=strrep(in,needle,replacement);
end
function write_json(path,value)
fid=fopen(path,'w');assert(fid>=0);fprintf(fid,'%s',jsonencode(value));fclose(fid);
end
