function save_Europa_state(out,step,time_years,flow_time_years,T,phi,H,Grid,d,DT,Tt,vs,vf,qr,head,p,overpressure,eta0,DThermal,kc,exponent)
% Read-only exporter. Flow comes from the start of the explicit transport step.
folder=fullfile(out,'states');if ~isfolder(folder),mkdir(folder);end
velocity_scale=DThermal/d;pressure_scale=eta0*DThermal/d^2;
state=struct('step',step,'time_years',time_years,'flow_time_years',flow_time_years, ...
 'temperature_K',T*DT+Tt,'phi',phi,'enthalpy_dimensionless',H,'Grid',Grid, ...
 'radius_m',Grid.p.xc*d,'elevation_m',Grid.p.yc*d,'length_scale_m',d, ...
 'solid_velocity_m_s',vs*velocity_scale,'fluid_velocity_m_s',vf*velocity_scale, ...
 'darcy_flux_m_s',qr*velocity_scale,'pressure_head_Pa',head*pressure_scale, ...
 'fluid_pressure_Pa',p*pressure_scale,'overpressure_Pa',overpressure, ...
 'velocity_scale_m_s',velocity_scale,'pressure_scale_Pa',pressure_scale, ...
 'kc_m2',kc,'permeability_exponent',exponent);
save(fullfile(folder,sprintf('state_%08d.mat',step)),'state','-v7.3');
end
